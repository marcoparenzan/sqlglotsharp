"""Translate the assignment-only TokenizerCore constructor/reset from the pinned AST."""
import ast
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import port_status

root = Path(__file__).resolve().parents[2]
source = ast.parse((root / 'python/sqlglot/tokenizer_core.py').read_text(encoding='utf-8'))
cls = next(n for n in source.body if isinstance(n, ast.ClassDef) and n.name == 'TokenizerCore')
init = next(n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == '__init__')
reset = next(n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == 'reset')
params = [p.arg for p in init.args.args if p.arg != 'self']
types = {}
for p in params:
    if p in ('single_tokens', 'keywords'): types[p] = 'PyDict<string, TokenType>'
    elif p in ('quotes', 'identifiers', 'numeric_literals', 'unescaped_sequences'): types[p] = 'PyDict<string, string>'
    elif p == 'comments': types[p] = 'PyDict<string, string?>'
    elif p == 'format_strings': types[p] = 'PyDict<string, (string, TokenType)>'
    elif p == 'numeric_escapes': types[p] = 'PyDict<string, (int, int, int, int)>'
    elif p == 'keyword_trie': types[p] = 'PyDict<object, object?>'
    elif p in ('commands', 'command_prefix_tokens', 'tokens_preceding_hint'): types[p] = 'HashSet<TokenType>'
    elif p in ('string_escapes', 'byte_string_escapes', 'identifier_escapes', 'var_single_tokens'): types[p] = 'HashSet<string>'
    elif p in ('hint_start', 'lone_surrogate_replacement'): types[p] = 'string'
    elif p == 'heredoc_string_alternative': types[p] = 'TokenType'
    else: types[p] = 'bool'
types.update(sql='string', size='int', tokens='List<Token>', _start='int', _current='int', _line='int', _col='int',
             _comments='List<string>', _char='string', _end='bool', _peek='string', _prev_token_line='int')

def assignment(n):
    if isinstance(n, ast.Assign):
        assert len(n.targets) == 1
        target, value = n.targets[0], n.value
    elif isinstance(n, ast.AnnAssign): target, value = n.target, n.value
    else: raise ValueError(f'Not an assignment: {ast.dump(n)}')
    assert isinstance(target, ast.Attribute) and isinstance(target.value, ast.Name) and target.value.id == 'self'
    if isinstance(value, ast.Name): expression = value.id
    elif isinstance(value, ast.Constant):
        import json
        expression = json.dumps(value.value)
    elif isinstance(value, ast.List) and not value.elts: expression = '[]'
    elif isinstance(value, ast.UnaryOp) and isinstance(value.op, ast.USub) and isinstance(value.operand, ast.Constant): expression = str(-value.operand.value)
    else: raise ValueError(f'Unsupported expression: {ast.dump(value)}')
    return f'            this.{target.attr} = {expression};'

# Hash API is deliberately queried through the existing CLI, avoiding a second hash algorithm.
import subprocess

def anchor(member):
    key = 'sqlglot/tokenizer_core.py::TokenizerCore' + ('.' + member if member else '')
    digest = subprocess.check_output([sys.executable, '-B', str(root / 'src/tools/port_status.py'), '--hash', key], text=True).strip()
    return f'        // py: {key} #{digest}'

lines = ['// Generated by src/tools/gen_tokenizer_state.py (assignment-only AST translation).', '#nullable enable', 'namespace SqlGlotSharp;', 'public static partial class tokenizer_core', '{', anchor(''), '    public partial class TokenizerCore', '    {', anchor('__slots__'), '        // Python slots are represented by the fields below.']
lines += [f'        public {t} {name};' for name,t in types.items()]
lines += [anchor('__init__'), '        public TokenizerCore(', ',\n'.join(f'            {types[p]} {p}' for p in params) + ')', '        {']
lines += [assignment(n) for n in init.body]
lines += ['        }', anchor('reset'), '        public void reset()', '        {']
lines += [assignment(n) for n in reset.body]
lines += ['        }', '    }', '}']
(root / 'src/SqlGlotSharp/tokenizer_core.state.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
