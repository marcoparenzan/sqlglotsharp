"""Generate C# enums and expression/trait declarations from the upstream runtime.

Constructors, metadata, merged data tables and registries remain pending.
Generated files must only be changed by rerunning this script.
"""
from __future__ import annotations

import argparse
import ast
import enum
import importlib
import hashlib
import json
import sys
from pathlib import Path

import port_status

KEYWORDS = set('abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while'.split())
HEADER = '// <auto-generated> Generated by src/tools/gen_csharp.py; do not edit. </auto-generated>\n#nullable enable\n'
WRITTEN = set()


def write_generated(path, content, encoding='utf-8'):
    path.write_text(content, encoding=encoding)
    WRITTEN.add(path.resolve())


def finalize_generated(output, manifest_path):
    output = output.resolve()
    removed = []
    for path in sorted(output.rglob('*.g.cs')):
        if path.resolve() not in WRITTEN and path.read_text(encoding='utf-8').startswith(HEADER):
            removed.append(path.relative_to(output).as_posix())
            path.unlink()
    files = [{'path': path.relative_to(output).as_posix(), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
             for path in sorted(WRITTEN) if path.is_relative_to(output)]
    manifest_path.write_text(json.dumps({'schema_version': 1, 'files': files}, indent=2) + '\n', encoding='utf-8')
    print(f'Generation manifest: {len(files)} files; removed {len(removed)} obsolete owned files.')


def identifier(name):
    if not name.isidentifier() or not name.isascii():
        raise ValueError(f'Unsupported C# identifier: {name}')
    return '@' + name if name in KEYWORDS else name


def literal(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, int):
        return str(value)
    raise ValueError(f'Unsupported enum value: {value!r}')


def render_enum(name, members, anchor, hashes):
    numeric = all(isinstance(value, int) for _, value in members)
    lines = []

    def mark(key):
        if key not in hashes:
            raise ValueError(f'Missing source anchor {key}')
        lines.append(f'    // py: {key} #{hashes[key]}')
    mark(anchor)
    lines.extend([f'    public enum {identifier(name)}' + (' : long' if numeric else ''), '    {'])
    string_values = {}
    for index, (member, value) in enumerate(members):
        if not numeric:
            string_values.setdefault(value, len(string_values) + 1)
        key = anchor + '.' + member
        if key in hashes:
            lines.append(f'        // py: {key} #{hashes[key]}')
        lines.append(f'        {identifier(member)} = {literal(value) if numeric else string_values[value]},')
    lines.append('    }')
    if not numeric:
        if not all(isinstance(value, str) for _, value in members):
            raise ValueError(f'Mixed enum values unsupported: {name}')
        # Helpers are conversion support, not extra Python members/anchors.
        lines.extend([f'    public static string ToValue({identifier(name)} value) => value switch', '    {'])
        seen = set()
        for member, value in members:
            if value in seen:
                continue
            seen.add(value)
            lines.append(f'        {identifier(name)}.{identifier(member)} => {literal(value)},')
        lines.extend(['        _ => throw new ArgumentOutOfRangeException(nameof(value)),', '    };',
                      f'    public static {identifier(name)} {identifier(name)}FromValue(string value) => value switch', '    {'])
        seen.clear()
        for member, value in members:
            if value not in seen:
                lines.append(f'        {literal(value)} => {identifier(name)}.{identifier(member)},')
                seen.add(value)
        lines.extend(['        _ => throw new ArgumentException("Unknown enum value", nameof(value)),', '    };'])
    return '\n'.join(lines) + '\n'


def generate(upstream, scope, output):
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(upstream.resolve()))
    hashes = {row['anchor']: row['hash'] for row in port_status.inventory(upstream, scope)}
    manifest = []
    for module_name in scope['modules']:
        module = importlib.import_module(module_name)
        file = scope['details'][module_name]['path']
        rendered = []
        for name, value in vars(module).items():
            if not isinstance(value, type) or not issubclass(value, enum.Enum) or value.__module__ != module_name or value.__name__ != name:
                continue
            members = [(key, item.value) for key, item in value.__members__.items()]
            if not members:
                continue
            rendered.append(render_enum(name, members, file + '::' + name, hashes))
            manifest.append({'module': module_name, 'name': name, 'members': members})
        if not rendered:
            continue
        parts = file.removeprefix('sqlglot/').split('/')
        if parts[0] == 'expressions':
            namespace, container = 'SqlGlotSharp', 'exp'
        else:
            namespace = 'SqlGlotSharp' + ('.' + '.'.join(parts[:-1]) if len(parts) > 1 else '')
            container = Path(parts[-1]).stem
        destination = output / Path(*parts).with_suffix('.enums.g.cs')
        destination.parent.mkdir(parents=True, exist_ok=True)
        write_generated(destination, HEADER + f'namespace {namespace};\n\npublic static partial class {identifier(container)}\n{{\n' + '\n'.join(rendered) + '}\n', encoding='utf-8')
    return manifest


def expression_model(upstream, scope):
    """Read trait markers statically and class inheritance from the upstream runtime."""
    expression_module = importlib.import_module('sqlglot.expressions')
    root = expression_module.Expr
    models = []
    for module_name in scope['modules']:
        if not module_name.startswith('sqlglot.expressions.'):
            continue
        path = scope['details'][module_name]['path']
        tree = ast.parse((upstream / path).read_text(encoding='utf-8'))
        module = importlib.import_module(module_name)
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            cls = getattr(module, node.name)
            if not isinstance(cls, type) or not issubclass(cls, root):
                continue
            is_trait = any(isinstance(d, ast.Name) and d.id == 'trait' for d in node.decorator_list)
            models.append({'name': node.name, 'path': path, 'trait': is_trait and node.name != 'Expr',
                           'bases': [base.__name__ for base in cls.__bases__ if base is not object],
                           'doc': ast.get_docstring(node, clean=False),
                           'metadata': {
                               'key': cls.key,
                               'arg_types': dict(cls.arg_types),
                               'required_args': sorted(cls.required_args),
                               'is_var_len_args': cls.is_var_len_args,
                               'is_primitive': cls.is_primitive,
                               '_hash_raw_args': cls._hash_raw_args,
                               'is_subquery': cls.is_subquery,
                               'is_cast': cls.is_cast,
                               'is_data_type': cls.is_data_type,
                               'var_len_arg_key': cls.var_len_arg_key,
                               '_sql_names': list(getattr(cls, '_sql_names', [])),
                               'sql_names__helper': list(cls.sql_names()) if issubclass(cls, expression_module.Func) and cls is not expression_module.Func else [],
                           }})
    return models


def render_shells(models, hashes):
    by_name = {model['name']: model for model in models}
    if len(by_name) != len(models):
        raise ValueError('Duplicate expression class names')
    files = {}
    for model in models:
        name = model['name']
        anchor = model['path'] + '::' + name
        if anchor not in hashes:
            raise ValueError('Missing class anchor: ' + anchor)
        trait_bases, concrete_bases = [], []
        for base in model['bases']:
            if base not in by_name:
                raise ValueError(f'Unknown expression base {base} for {name}')
            if by_name[base]['trait']:
                trait_bases.append(base)
            elif not model['trait']:
                concrete_bases.append(base)
        if len(concrete_bases) > 1:
            raise ValueError(f'Multiple concrete bases for {name}: {concrete_bases}')
        bases = trait_bases if model['trait'] else concrete_bases + trait_bases
        if name == 'Expr':
            declaration = 'public abstract partial class Expr'
        elif model['trait']:
            declaration = 'public interface ' + identifier(name)
        else:
            declaration = 'public partial class ' + identifier(name)
        if bases:
            declaration += ' : ' + ', '.join(identifier(base) for base in bases)
        lines = []
        if model['doc']:
            from xml.sax.saxutils import escape
            lines.append('    /// <summary>')
            lines.extend('    /// ' + escape(line) for line in model['doc'].splitlines())
            lines.append('    /// </summary>')
        lines.extend([f'    // py: {anchor} #{hashes[anchor]}', '    ' + declaration, '    {', '    }'])
        files.setdefault(model['path'], []).append('\n'.join(lines))
    return {path: HEADER + 'namespace SqlGlotSharp;\n\npublic static partial class exp\n{\n' + '\n\n'.join(items) + '\n}\n' for path, items in files.items()}


def render_metadata(models, hashes):
    """Expose runtime metadata through virtual properties, with static backing data."""
    files = {}
    for model in models:
        if model['trait']:
            continue
        name = model['name']
        values = model['metadata']
        declarations = [f'    public {"abstract " if name == "Expr" else ""}partial class {identifier(name)}', '    {']
        for key, value in values.items():
            if key == 'arg_types':
                type_name = 'PyDict<string, bool>'
                expression = 'new() { ' + ', '.join('[' + literal(k) + '] = ' + str(v).lower() for k, v in value.items()) + ' }'
            elif key == 'required_args':
                type_name = 'HashSet<string>'
                expression = 'new(StringComparer.Ordinal) { ' + ', '.join(literal(v) for v in value) + ' }'
            elif key in ('_sql_names', 'sql_names__helper'):
                type_name = 'List<string>'
                expression = '[' + ', '.join(literal(v) for v in value) + ']'
            elif isinstance(value, bool):
                type_name, expression = 'bool', str(value).lower()
            elif isinstance(value, str):
                type_name, expression = 'string', literal(value)
            else:
                raise ValueError(f'Unsupported metadata {name}.{key}: {value!r}')
            anchor = model['path'] + '::' + name + '.' + key
            if anchor in hashes:
                declarations.append(f'        // py: {anchor} #{hashes[anchor]}')
            modifier = '' if name == 'Expr' else 'new '
            declarations.append(f'        public static {modifier}readonly {type_name} {identifier(key + "_")} = {expression};')
            virtual = 'virtual' if name == 'Expr' else 'override'
            declarations.append(f'        public {virtual} {type_name} {identifier(key)} => {identifier(key + "_")};')
        declarations.append('    }')
        files.setdefault(model['path'], []).append('\n'.join(declarations))
    return {path: HEADER + 'namespace SqlGlotSharp;\n\npublic static partial class exp\n{\n' + '\n\n'.join(items) + '\n}\n' for path, items in files.items()}


def render_constructors(models):
    files = {}
    for model in models:
        if model['trait'] or model['name'] == 'Expr':
            continue
        name = identifier(model['name'])
        keys = list(model['metadata']['arg_types'])
        # DateTrunc normalizes kwargs before Expr establishes parent links.
        base_args = '_constructor_args'
        if model['name'] == 'DateTrunc':
            keys.append('unabbreviate')
            base_args = 'DateTrunc__init__helper(_constructor_args)'
        parameters = ', '.join(f'[System.Runtime.InteropServices.Optional] object? {identifier(key)}' for key in keys)
        pairs = ', '.join(f'({literal(key)}, {identifier(key)})' for key in keys)
        lines = [f'    public partial class {name}', '    {',
                 f'        public {name}(PyDict<string, object?> _constructor_args) : base({base_args}) {{ }}',
                 f'        public {name}({parameters}) : this(constructor_args__helper({pairs})) {{ }}', '    }']
        files.setdefault(model['path'], []).append('\n'.join(lines))
    return {path: HEADER + 'namespace SqlGlotSharp;\n\npublic static partial class exp\n{\n' + '\n\n'.join(items) + '\n}\n' for path, items in files.items()}


def generate_expression_shells(upstream, scope, output):
    models = expression_model(upstream, scope)
    hashes = {row['anchor']: row['hash'] for row in port_status.inventory(upstream, scope)}
    rendered = render_shells(models, hashes)
    for path, content in rendered.items():
        destination = output / Path(path.removeprefix('sqlglot/')).with_suffix('.shells.g.cs')
        destination.parent.mkdir(parents=True, exist_ok=True)
        write_generated(destination, content, encoding='utf-8')
    for path, content in render_metadata(models, hashes).items():
        destination = output / Path(path.removeprefix('sqlglot/')).with_suffix('.meta.g.cs')
        destination.parent.mkdir(parents=True, exist_ok=True)
        write_generated(destination, content, encoding='utf-8')
    for path, content in render_constructors(models).items():
        destination = output / Path(path.removeprefix('sqlglot/')).with_suffix('.constructors.g.cs')
        write_generated(destination, content, encoding='utf-8')
    module = importlib.import_module('sqlglot.expressions')
    names = {model['name'] for model in models}
    entries = []
    for key, cls in module.EXPR_CLASSES.items():
        if cls.__name__ not in names:
            raise ValueError('Unknown registry class: ' + cls.__name__)
        entries.append(f'        [{literal(key)}] = typeof({identifier(cls.__name__)}),')
    anchor = 'sqlglot/expressions/__init__.py::EXPR_CLASSES'
    content = HEADER + 'namespace SqlGlotSharp;\n\npublic static partial class exp\n{\n'
    content += f'    // py: {anchor} #{hashes[anchor]}\n'
    content += '    public static readonly PyDict<string, Type> EXPR_CLASSES = new()\n    {\n' + '\n'.join(entries) + '\n    };\n}\n'
    write_generated(output / 'expressions' / '__init__.registry.g.cs', content, encoding='utf-8')
    trait = module.TimeUnit
    content = HEADER + 'namespace SqlGlotSharp;\n\npublic static partial class exp\n{\n    public abstract partial class Expr\n    {\n'
    for name in ('UNABBREVIATED_UNIT_NAME', 'VAR_LIKE'):
        anchor = 'sqlglot/expressions/core.py::TimeUnit.' + name
        content += f'        // py: {anchor} #{hashes[anchor]}\n'
        if name == 'UNABBREVIATED_UNIT_NAME':
            entries = ', '.join('[' + literal(k) + '] = ' + literal(v) for k, v in getattr(trait, name).items())
            content += '        private static readonly PyDict<string, string> TimeUnit_UNABBREVIATED_UNIT_NAME__helper = new() { ' + entries + ' };\n'
        else:
            entries = ', '.join('typeof(' + identifier(cls.__name__) + ')' for cls in trait.VAR_LIKE)
            content += '        private static readonly HashSet<Type> TimeUnit_VAR_LIKE__helper = [' + entries + '];\n'
    content += '    }\n}\n'
    write_generated(output / 'expressions' / 'core.timeunit.data.g.cs', content, encoding='utf-8')
    print(f'Generated {len(module.EXPR_CLASSES)} expression registry entries.')
    print(f'Generated {len(models)} expression declarations ({sum(model["trait"] for model in models)} trait interfaces) with metadata, constructors and TimeUnit normalization data.')


def generate_enum_aliases(scope, output, hashes):
    """C# has no public nested type aliases: expose constants of the original enum."""
    import gen_data
    module = importlib.import_module('sqlglot.expressions')
    aliases = []
    for cls in set(module.EXPR_CLASSES.values()):
        for name, value in vars(cls).items():
            if isinstance(value, type) and issubclass(value, enum.Enum):
                aliases.append((cls, name, value))
    content = HEADER + 'namespace SqlGlotSharp;\npublic static partial class exp\n{\n'
    for cls, name, enum_type in sorted(aliases, key=lambda item: (item[0].__name__, item[1])):
        path = scope['details'][cls.__module__]['path']
        anchor = path + '::' + cls.__name__ + '.' + name
        content += f'    public partial class {identifier(cls.__name__)}\n    {{\n'
        content += f'        // py: {anchor} #{hashes[anchor]}\n'
        content += f'        public static class {identifier(name)}\n        {{\n'
        for member in enum_type.__members__:
            target = gen_data.qualified(enum_type)
            content += f'            public const {target} {identifier(member)} = {target}.{identifier(member)};\n'
        content += '        }\n    }\n'
    content += '}\n'
    write_generated(output / 'expressions' / '__init__.enumaliases.g.cs', content, encoding='utf-8')
    print(f'Generated {len(aliases)} nested enum alias constant tables (no distinct nested enums in this baseline).')


def main():
    repo = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream', type=Path, default=repo / 'python')
    parser.add_argument('--scope', type=Path, default=Path(__file__).with_name('scope.json'))
    parser.add_argument('--output', type=Path, default=repo / 'src' / 'SqlGlotSharp')
    args = parser.parse_args()
    scope = json.loads(args.scope.read_text(encoding='utf-8'))
    manifest = generate(args.upstream, scope, args.output)
    print(f'Generated {len(manifest)} top-level enums, {sum(len(item["members"]) for item in manifest)} values.')
    generate_expression_shells(args.upstream, scope, args.output)
    import gen_data
    hashes = {row['anchor']: row['hash'] for row in port_status.inventory(args.upstream, scope)}
    gen_data.generate(args.upstream, scope, args.output, hashes, HEADER, identifier, literal, write_generated)
    generate_enum_aliases(scope, args.output, hashes)
    import gen_expression_data
    gen_expression_data.generate(args.upstream, scope, args.output, hashes, HEADER, identifier, literal,
                                 write_generated, expression_model(args.upstream, scope))
    finalize_generated(args.output, Path(__file__).with_name('generated_manifest.json'))


if __name__ == '__main__':
    main()
