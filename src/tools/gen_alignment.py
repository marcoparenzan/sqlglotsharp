"""Generate ALIGNMENT.md: the map between this C# port and the official SQLGlot (python/).

Inputs (all produced by existing tools):
  - port_status report (python src/tools/port_status.py --json > report.json)
  - src/tools/scope.json (modules in scope), UPSTREAM.json (baseline)
  - the latest scoreboard.json (corpus results)
  - the C# sources (// py: anchors), to detect members that are named but not hash-verified

Usage:
  python -B src/tools/gen_alignment.py [--status REPORT.json] [--score SCOREBOARD.json] [--output ALIGNMENT.md]
(defaults: docs/status/port_status.json and docs/status/scoreboard.json, output docs/ALIGNMENT.md)
"""
import argparse
import collections
import glob
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser()
ap.add_argument("--status", default=str(root / "docs/status/port_status.json"))
ap.add_argument("--score", default=str(root / "docs/status/scoreboard.json"))
ap.add_argument("--output", default=str(root / "docs" / "ALIGNMENT.md"))
args = ap.parse_args()

status = json.loads(Path(args.status).read_text(encoding="utf-8"))
score = json.loads(Path(args.score).read_text(encoding="utf-8"))
scope = json.loads((root / "src/tools/scope.json").read_text(encoding="utf-8"))
upstream = json.loads((root / "UPSTREAM.json").read_text(encoding="utf-8"))

# members that carry a "// py:" anchor (any hash) in the C# sources
named = set()
named_files = collections.defaultdict(collections.Counter)
rx = re.compile(r"//\s*py:\s*(\S+?::[\w.\[\]]+)")
for f in glob.glob(str(root / "src/SqlGlotSharp/**/*.cs"), recursive=True):
    rel_file = Path(f).relative_to(root / "src/SqlGlotSharp").as_posix()
    for line in open(f, encoding="utf-8", errors="ignore"):
        for m in rx.finditer(line):
            named.add(m.group(1))
            named_files[m.group(1).split("::")[0]][rel_file] += 1

per_file = collections.defaultdict(collections.Counter)
csharp_files = collections.defaultdict(collections.Counter)
for m in status["members"]:
    p = m["path"]
    st = m["status"]
    if st == "missing" and m["anchor"] in named:
        st = "named"
    per_file[p][st] += 1
    for c in m.get("csharp", []):
        csharp_files[p][c["file"]] += 1

SCOPE_NOTES = {
    "sqlglot/optimizer/scope.py": "Not ported: scope traversal (only walk_in_scope/find_all_in_scope are mirrored privately). Annotating whole queries raises NotPortedException.",
    "sqlglot/optimizer/annotate_types.py": "Expression-level TypeAnnotator ported; scope/pivot/column lookup paths are NotPorted.",
    "sqlglot/optimizer/simplify.py": "All Simplifier rules ported; date/interval arithmetic (dateutil) and constant propagation are NotPorted.",
    "sqlglot/schema.py": "Not ported: only a schema-less stand-in (typing.ExpressionSchema) exists.",
    "sqlglot/dialects/dialect.py": "Base Dialect ported with host extension points (CreateParser/CreateGenerator/CreateTokenizer, register/unregister).",
    "sqlglot/generators/tsql.py": "Ported by behaviour (corpus 3,166/3,166); anchors carry no hash for the newer files.",
    "sqlglot/parsers/tsql.py": "Ported by behaviour (corpus 3,166/3,166); anchors carry no hash for the newer files.",
}

dialect_dir = root / "python/sqlglot/dialects"
official_dialects = sorted(p.stem for p in dialect_dir.glob("*.py") if p.stem not in ("__init__", "dialect"))
ported_dialects = {"postgres": "ported", "tsql": "ported", "fabric": "ported"}

# corpus results
by_dialect = collections.defaultdict(lambda: [0, 0, 0, 0])
for r in score:
    t = by_dialect[r["Dialect"]]
    t[0] += r["Passed"]; t[1] += r["Failed"]; t[2] += r["NotPorted"]; t[3] += r["Total"]
levels = collections.defaultdict(dict)
for r in score:
    levels[r["Dialect"]][r["Level"]] = r

lines = []
w = lines.append
w("# ALIGNMENT — C# port vs official SQLGlot")
w("")
w("Generated by `src/tools/gen_alignment.py` (regenerate after each block). Do not edit by hand.")
w("")
w("## 1. Baseline")
w("")
w("| Item | Value |")
w("|---|---|")
w(f"| Official repository | {upstream['repo']} |")
w(f"| Official tag / commit | `{upstream['tag']}` / `{upstream['commit']}` (read-only in `python/`) |")
w(f"| Target framework | `{upstream['target_framework']}` (exception to the .NET 11 rule, agreed with the owner) |")
w("| Naming | Python names are preserved (`snake_case` methods, `UPPER_CASE` tables); every member carries a `// py: path::Name #hash` anchor |")
w("| Verification | Corpus recorded from the Python test suite (L1 parse, L2 generate/transpile, L3 helper cases), plus unit tests with oracle values |")
w("")
w("## 2. Result at a glance")
w("")
w("Levels L0 (tokenizer) to L3 (helper cases), all corpus dialects.")
w("")
w("| Dialect | Passed | Failed | NotPorted | Total |")
w("|---|---:|---:|---:|---:|")
for d, t in sorted(by_dialect.items()):
    name = d or "base"
    w(f"| {name} | {t[0]:,} | {t[1]} | {t[2]} | {t[3]:,} |")
tot = [sum(t[i] for t in by_dialect.values()) for i in range(4)]
w(f"| **all** | **{tot[0]:,}** | **{tot[1]}** | **{tot[2]}** | **{tot[3]:,}** |")
w("")
w("The corpus is the functional measure. The anchor counts below are only a coverage heuristic (see section 4).")
w("")
w("## 3. Dialect map")
w("")
w("| Official dialect | Port status |")
w("|---|---|")
w("| base (`dialect.py`, `\"\"`) | ported, 100% of corpus |")
for d in official_dialects:
    w(f"| {d} | {ported_dialects.get(d, 'out of scope (raises NotPortedException)')} |")
w("")
w("Host-only dialects (not in the official project):")
w("")
w("| Dialect | What it is |")
w("|---|---|")
w("| `timescale` | PostgreSQL + `time_bucket`; identity, DDL and a proven fixed-width `DATE_BIN` rewrite |")
w("| `layer3` | extension project `SqlGlotSharp.Extensions.Layer3` (registered by `Layer3.Register()`): base + `MEMBER OF` -> `JSONArrayContains`; checked against the oracle-generated expectations and, when present, the host `corpus.json` (sqlglot 30.23.0) |")
w("")
w("## 4. Module map")
w("")
w("Anchor states per official module: **ported** = anchor with matching hash; **stub** = anchor with a zero hash (implemented, completeness not hash-proven);")
w("**named** = member referenced by a `// py:` comment without a verified hash; **missing** = no reference in the C# sources.")
w("")
w("| Official module | ported | stub | named | missing | Main C# files | Note |")
w("|---|---:|---:|---:|---:|---|---|")
for p, c in sorted(per_file.items(), key=lambda kv: (-sum(kv[1].values()), kv[0])):
    merged = collections.Counter(csharp_files[p])
    merged.update(named_files.get(p, {}))
    files = ", ".join(f"`{f}`" for f, _ in merged.most_common(3)) or "-"
    w(f"| `{p}` | {c['ported']} | {c['stub']} | {c['named']} | {c['missing']} | {files} | {SCOPE_NOTES.get(p, '')} |")
tc = collections.Counter()
for c in per_file.values():
    tc.update(c)
w(f"| **total** | **{tc['ported']}** | **{tc['stub']}** | **{tc['named']}** | **{tc['missing']}** | | |")
w("")
w("## 5. Out of scope (official modules with no counterpart)")
w("")
in_scope = {m for m in scope["modules"]} if isinstance(scope["modules"], dict) else set(scope["modules"])
outside = []
for f in sorted((root / "python/sqlglot").rglob("*.py")):
    rel = f.relative_to(root / "python").as_posix()
    if rel not in per_file and "/dialects/" not in rel and "__pycache__" not in rel:
        outside.append(rel)
groups = collections.defaultdict(list)
for rel in outside:
    parts = rel.split("/")
    key = "/".join(parts[:2]) + "/*" if len(parts) > 2 and parts[1] in ("generators", "parsers", "typing") else rel
    groups[key].append(rel)
for key, items in groups.items():
    w(f"- `{key}`" + (f" ({len(items)} files)" if len(items) > 1 else ""))
w("")
w("## 6. Differences from the official project")
w("")
w("| Area | Difference |")
w("|---|---|")
w("| Extension | `Dialect.CreateParser/CreateGenerator/CreateTokenizer` are virtual (Python uses class attributes); `Dialect.register/unregister` |")
w("| API | `exp.column(...)`, `Expr.sql(dialect)`, `SqlGlot.transpile/parse_one` mirror the Python names; PascalCase aliases exist only on `SqlGlot` |")
w("| Optimizer | Subset: `TypeAnnotator` (expression level) and `Simplifier` (without date/interval and constant propagation) |")
w("| Registry | Only base, postgres, tsql, fabric, timescale are built in (extensions such as `layer3` register themselves); other official names raise `NotPortedException` |")
w("| Errors | Unported grammar or transforms raise `NotPortedException`; there is never a silent fallback |")
w("| Hash anchors | Files written after the generator era use `// py: path::Name` without a hash, so section 4 under-reports them |")
w("")
# ---- upstream drift: tags newer than the baseline, from the read-only python/ clone ----
import subprocess

def git(*a):
    r = subprocess.run(["git", "-C", str(root / "python"), *a], capture_output=True, text=True)
    return r.stdout.strip()

baseline = upstream["tag"]
newer = [t for t in git("tag", "--sort=version:refname").splitlines()
         if re.fullmatch(r"v\d+\.\d+\.\d+", t) and tuple(map(int, t[1:].split("."))) > tuple(map(int, baseline[1:].split(".")))]
scope_files = []
for mod in scope["modules"]:
    for cand in (mod.replace(".", "/") + ".py", mod.replace(".", "/") + "/__init__.py"):
        if (root / "python" / cand).exists():
            scope_files.append(cand)
scope_files += ["sqlglot/generators/tsql.py", "sqlglot/generators/fabric.py", "sqlglot/parsers/tsql.py",
                "sqlglot/parsers/fabric.py", "sqlglot/typing/tsql.py", "sqlglot/typing/postgres.py"]
in_scope_dialects = {"postgres", "postgresql", "tsql", "fabric", "base", "generator", "parser", "tokens", "expressions", "expression", "jsonpath", "describe", "pivot", "optimizer", "typing"}

w("## 7. Drift from newer official releases")
w("")
if not newer:
    w(f"No official release newer than `{baseline}` is present in the local `python/` clone.")
else:
    w(f"Releases in the local `python/` clone newer than the baseline `{baseline}`; only files in scope are counted.")
    w("")
    for tag in newer:
        rows = [r.split("	") for r in git("diff", "--numstat", baseline, tag, "--", *scope_files).splitlines() if r]
        total_all = len(git("diff", "--numstat", baseline, tag, "--", "sqlglot").splitlines())
        w(f"### `{baseline}` -> `{tag}`")
        w("")
        w(f"{len(rows)} of {len(scope_files)} in-scope files changed ({total_all} files of the whole `sqlglot/` package).")
        w("")
        if rows:
            w("| In-scope file | + | - |")
            w("|---|---:|---:|")
            for add_, del_, name in rows:
                w(f"| `{name}` | {add_} | {del_} |")
            w("")
            w("Commits touching those files (an action is needed unless the change is for a dialect outside the port):")
            w("")
            for line in git("log", "--oneline", f"{baseline}..{tag}", "--", *[r[2] for r in rows]).splitlines():
                subject = line.split(" ", 1)[1] if " " in line else line
                m = re.match(r"\w+\((\w+)\)", subject)
                action = "no action (dialect out of scope)" if m and m.group(1).lower() not in in_scope_dialects else "review"
                w(f"- `{line[:9]}` {subject} - **{action}**")
            w("")
w("## 8. Realignment procedure (new official release)")
w("")
w("The full procedure, the triage rules and the sync log are in [UPSTREAM-SYNC.md](UPSTREAM-SYNC.md). In short:")
w("")
w("1. In `python/` (read-only, git-ignored): `git fetch --tags` and `git checkout <new-tag>`; update `UPSTREAM.json` (tag, commit).")
w("2. Re-record the corpus with the oracle (`src/tools/extract_corpus.py`, environment: `src/tools/run-oracle.ps1`), into a fresh directory outside the repository.")
w("3. Run the Scoreboard on the new corpus: every difference is a `Fail` or `NotPorted` and `notported.json` is the work list.")
w("4. Regenerate the generated files (`src/tools/gen_csharp.py`, `gen_typing_metadata.py`) and rebuild; stale anchors show up in `port_status.py`.")
w("5. Port the changed members (section 7 lists them), keeping the `// py:` anchors; add oracle-based tests for each behaviour change.")
w("6. Re-run the unit tests and the full Scoreboard until `Fail = 0` and `NotPorted = 0`, a full run without an output argument writes to `docs/status/`, rerun `gen_alignment.py`.")
w("7. The host `layer3` corpus (`corpus.json`, recorded with sqlglot 30.23.0) is compared against the new release: regenerate `src/SqlGlotSharp.Extensions.Layer3.Tests/Layer3/expected.json` with `gen_layer3_expected.py` and review any difference.")
w("")
w("## 9. Regenerating this map")
w("")
w("```powershell")
w("$py = 'artifacts/oracle-venv/Scripts/python.exe'")
w("& $py -B src/tools/port_status.py --json > docs/status/port_status.json")
w("# the Scoreboard writes scoreboard.json to docs/status when run without an output argument")
w("& $py -B src/tools/gen_alignment.py")
w("```")
Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", args.output, len(lines), "lines")
