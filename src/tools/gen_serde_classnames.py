"""Generate qualified Python expression class names for faithful serde payloads."""
import inspect
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
sys.path.insert(0, str(root / 'python'))
from sqlglot import exp
classes = {c for _, c in inspect.getmembers(exp, lambda c: inspect.isclass(c) and issubclass(c, exp.Expr))}
lines = ['// Generated by src/tools/gen_serde_classnames.py', '#nullable enable', 'namespace SqlGlotSharp;', 'public static partial class serde', '{', '    private static readonly Dictionary<Type, string> ClassNames = new()', '    {']
for cls in sorted(classes, key=lambda c: (c.__module__, c.__qualname__)):
    name = cls.__qualname__ if cls.__module__ == exp.__name__ else cls.__module__ + '.' + cls.__qualname__
    lines.append(f'        [typeof(exp.{cls.__name__})] = "{name}",')
lines += ['    };', '}']
(root / 'src/SqlGlotSharp/serde.classnames.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
