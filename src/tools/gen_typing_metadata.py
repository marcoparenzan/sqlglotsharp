"""Translate pure typing metadata and its small lambda language into C# delegates."""
import ast
import inspect
import json
import subprocess
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
sys.path.insert(0, str(root / 'python'))
import sqlglot.typing as source
from sqlglot import exp
module = ast.parse((root / 'python/sqlglot/typing/__init__.py').read_text(encoding='utf-8'))
lambdas = {n.lineno: n for n in ast.walk(module) if isinstance(n, ast.Lambda)}
methods = set()

def render(node):
    if isinstance(node, ast.Name): return node.id
    if isinstance(node, ast.Constant): return json.dumps(node.value)
    if isinstance(node, ast.Attribute): return render(node.value) + '.' + node.attr
    if isinstance(node, ast.Subscript): return render(node.value) + '[' + render(node.slice) + ']!'
    if isinstance(node, ast.IfExp): return '(py.truthy(' + render(node.test) + ') ? (object?)' + render(node.body) + ' : ' + render(node.orelse) + ')'
    if isinstance(node, ast.ListComp):
        assert len(node.generators) == 1
        generator = node.generators[0]
        assert not generator.ifs
        name = generator.target.id
        return '((IEnumerable<object?>)' + render(generator.iter) + ').Cast<exp.Expr>().Select(' + name + ' => ' + render(node.elt) + ')'
    if isinstance(node, ast.Call):
        method = render(node.func)
        if method.startswith('self._'): methods.add(node.func.attr)
        if method == 'self._annotate_by_args':
            flags = {kw.arg: render(kw.value) for kw in node.keywords}
            segments = []
            for argument in node.args[1:]:
                segments.append(render(argument.value) if isinstance(argument, ast.Starred) else 'new object?[] { ' + render(argument) + ' }')
            args = segments[0] if segments else 'Array.Empty<object?>()'
            for segment in segments[1:]: args = '(' + args + ').Concat(' + segment + ')'
            return method + '(' + render(node.args[0]) + ', array: ' + flags.get('array', 'false') + ', promote: ' + flags.get('promote', 'false') + ', args: (' + args + ').ToArray())'
        assert not node.keywords
        return method + '(' + ', '.join(render(a) for a in node.args) + ')'
    raise ValueError('Unsupported typing expression: ' + ast.dump(node))

def anchor(member):
    key = 'sqlglot/typing/__init__.py::' + member
    digest = subprocess.check_output([sys.executable, '-B', str(root / 'src/tools/port_status.py'), '--hash', key], text=True).strip()
    return f'    // py: {key} #{digest}'

lines = ['// Generated by src/tools/gen_typing_metadata.py', '#nullable enable', 'namespace SqlGlotSharp;', 'public static partial class typing', '{', anchor('ExprMetadataType'), '    // ExprMetadataType is PyDict<Type, PyDict<string, object?>>.', anchor('TIMESTAMP_EXPRESSIONS'), '    public static readonly HashSet<Type> TIMESTAMP_EXPRESSIONS =', '    [']
lines += ['        typeof(exp.' + c.__name__ + '),' for c in sorted(source.TIMESTAMP_EXPRESSIONS, key=lambda c: c.__name__)]
lines += ['    ];', anchor('EXPRESSION_METADATA'), '    public static readonly PyDict<Type, PyDict<string, object?>> EXPRESSION_METADATA = new()', '    {']
for cls, metadata in source.EXPRESSION_METADATA.items():
    fields = []
    for key, value in metadata.items():
        if isinstance(value, exp.DType): expression = 'exp.DType.' + value.name
        elif callable(value):
            if value.__name__ != '<lambda>': expression = '(Annotation)' + value.__name__
            else: expression = '(Annotation)((self, e) => ' + render(lambdas[value.__code__.co_firstlineno].body) + ')'
        else: raise ValueError(f'Unsupported metadata {key}: {value}')
        fields.append('[' + json.dumps(key) + '] = ' + expression)
    lines.append('        [typeof(exp.' + cls.__name__ + ')] = new() { ' + ', '.join(fields) + ' },')
lines += ['    };', '}']
(root / 'src/SqlGlotSharp/typing/metadata.g.cs').parent.mkdir(parents=True, exist_ok=True)
(root / 'src/SqlGlotSharp/typing/metadata.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
(root / 'src/tools/typing_inventory.json').write_text(json.dumps({'classes': len(source.EXPRESSION_METADATA), 'returns': sum('returns' in v for v in source.EXPRESSION_METADATA.values()), 'annotators': sum('annotator' in v for v in source.EXPRESSION_METADATA.values()), 'backend_methods': sorted(methods)}, indent=2) + '\n', encoding='utf-8')
print('Typing metadata:', len(source.EXPRESSION_METADATA), 'classes; backend methods:', ', '.join(sorted(methods)))
