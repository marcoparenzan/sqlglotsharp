"""Generate pinned timezone data and representative time helper oracle cases."""
import json
import subprocess
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
sys.path.insert(0, str(root / 'python'))
from sqlglot import time
hash_ = subprocess.check_output([sys.executable, '-B', str(root / 'src/tools/port_status.py'), '--hash', 'sqlglot/time.py::TIMEZONES'], text=True).strip()
lines = ['// Generated by src/tools/gen_time_cases.py', 'namespace SqlGlotSharp;', 'public static partial class time', '{', f'    // py: sqlglot/time.py::TIMEZONES #{hash_}', '    public static readonly HashSet<string> TIMEZONES =', '    [']
lines += ['        ' + json.dumps(zone) + ',' for zone in sorted(time.TIMEZONES)]
lines += ['    ];', '}']
(root / 'src/SqlGlotSharp/time.data.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
formats = []
for mapping in ({'%Y':'YYYY','%m':'MM','%d':'DD'}, {'Y':'y','YY':'yy','YYYY':'year'}, {'ab':'X','abc':'Y','b':'Z'}):
    for value in ('', '%Y-%m-%d', 'YYYY-MM-DD', 'YYY', 'ababc', 'a', 'abcXab', '😀%Y'):
        formats.append({'input': value, 'mapping': mapping, 'expected': time.format_time(value, mapping)})
values = ['2023-01-01 12:13:14', '2023-01-01 12:13:14.123456+00:00', '2023-01-01 12:13:14.120000', '2023-01-01T12.000001', '2023-01-01T12.0000001', '2023-01-01T12:00:00+01:00:00.123456', 'invalid', '2023-02-29T12:00:00', '20240101T123456.12Z']
cases = {'formats': formats, 'precisions': [{'input': value, 'expected': time.subsecond_precision(value)} for value in values], 'timezone_count': len(time.TIMEZONES)}
(root / 'src/SqlGlotSharp.Tests/time-cases.json').write_text(json.dumps(cases, ensure_ascii=True, indent=2) + '\n', encoding='utf-8')
