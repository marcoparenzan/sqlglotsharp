"""Generate Unicode casing and context properties from the oracle Python runtime."""
import json
import sys
import unicodedata
from pathlib import Path
root = Path(__file__).resolve().parents[2]
upper, lower, cased, ignored, uppers, lowers, words = {}, {}, [], [], [], [], []
for cp in range(0x110000):
    char = chr(cp)
    up, lo = char.upper(), char.lower()
    if up != char: upper[cp] = up
    if lo != char: lower[cp] = lo
    if char.isupper(): uppers.append(cp)
    if char.islower(): lowers.append(cp)
    if char.isupper() or char.islower() or char.istitle(): cased.append(cp)
    # Probe the final-sigma context rule to derive Case_Ignorable from this
    # runtime, including code points that are both Cased and Case_Ignorable.
    if ('AΣ' + char + 'B').lower()[1] == 'σ' and ('AΣ' + char).lower()[1] == 'ς': ignored.append(cp)
    if char.isalnum() or char == '_': words.append(cp)

def ranges(values):
    result = []
    for cp in values:
        if result and result[-1][1] + 1 == cp: result[-1][1] = cp
        else: result.append([cp, cp])
    return result

lines = ['// Generated by src/tools/gen_unicode_case.py; oracle Unicode ' + unicodedata.unidata_version,
         '#nullable enable', 'namespace SqlGlotSharp;', 'public static partial class py', '{', '    private static class UnicodeCaseData', '    {']
for name, values in [('Upper', upper), ('Lower', lower)]:
    lines += [f'        internal static readonly Dictionary<int, string> {name} = new()', '        {']
    lines += [f'            [0x{cp:X}] = {json.dumps(value, ensure_ascii=True)},' for cp,value in values.items()]
    lines += ['        };']
for name, values in [('Cased', cased), ('Ignored', ignored), ('UpperChars', uppers), ('LowerChars', lowers), ('WordChars', words)]:
    lines += [f'        internal static readonly (int Start, int End)[] {name} =', '        [']
    lines += [f'            (0x{start:X}, 0x{end:X}),' for start,end in ranges(values)]
    lines += ['        ];']
lines += ['    }', '}']
(root / 'src/SqlGlotSharp/py/unicode.casing.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
values = ['', 'Foo', 'straße', 'İstanbul', 'ΟΣ', 'ΟΣΑ', "Ο'Σ", "AΣ'B", 'AΣ\u0345', 'AΣ\u0345B', 'Σ', 'ﬃ', 'Ⅳ', '😀a', '𐐨𐐀', 'ǅ', 'a𐐨', 'abc\n', 'abc\r\n', 'á']
values += [chr(cp) for cp in sorted(set(upper) | set(lower))]
import re
cases = [{'input': text, 'upper': text.upper(), 'lower': text.lower(), 'isupper': text.isupper(), 'islower': text.islower(), 'safe': bool(re.match(r'^[_a-zA-Z][\w]*$', text))} for text in values]
(root / 'src/SqlGlotSharp.Tests/unicode-case-cases.json').write_text(json.dumps(cases, ensure_ascii=True, indent=2) + '\n', encoding='utf-8')
print(f'Generated {len(upper)} upper mappings, {len(lower)} lower mappings; Unicode {unicodedata.unidata_version}')
