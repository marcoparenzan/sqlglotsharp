"""Record exported expression class names (includes Python trait classes)."""
import inspect
import sys
from pathlib import Path

repo = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
sys.path.insert(0, str(repo / 'python'))
from sqlglot import exp

lines = ['// Generated by src/tools/gen_expression_exports.py', 'namespace SqlGlotSharp;', 'public static partial class helper', '{', '    private static readonly (string Name, Type Type)[] ExpressionExports =', '    [']
for name, cls in inspect.getmembers(exp, lambda obj: inspect.isclass(obj) and issubclass(obj, exp.Expr)):
    lines.append(f'        ("{name}", typeof(exp.{cls.__name__})),')
lines += ['    ];', '}']
(repo / 'src/SqlGlotSharp/helper.exports.g.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
