    private static object Links(exp.Expr ast) => ast.walk().Select(n => new
    {
        key = n.key, parent = n.parent?.key, arg_key = n.arg_key, index = n.index
    }).ToArray();

    [Fact]
    public async Task Public_Postgres_and_Timescale_AST_SQL_reparse_and_copy_mutation_match_live_Python()
    {
        var cases = Queries.SelectMany(sql => new[] { "postgres", "timescale" }
            .SelectMany(dialect => new[] { false, true }.SelectMany(pretty => new[] { false, true }
                .Select(copy => new { sql, dialect, pretty, copy })))).ToArray();
        var expected = JsonNode.Parse(await Python("""
            import sys, json
            sys.path.insert(0, 'python')
            sys.path.insert(0, 'src/tools')
            from oracle_plugins.timescale import Timescale
            from sqlglot import parse_one
            from sqlglot.dialects import Dialect
            from sqlglot.serde import dump
            def links(ast):
                return [dict(key=n.key, parent=n.parent.key if n.parent else None,
                    arg_key=n.arg_key, index=n.index) for n in ast.walk()]
            results = []
            for c in json.load(sys.stdin):
                d = Dialect.get_or_raise(c['dialect'])
                ast = parse_one(c['sql'], read=d)
                before = dump(ast)
                g = d.generator(pretty=c['pretty'])
                sql = g.generate(ast, copy=c['copy'])
                after = dump(ast)
                state = links(ast)
                again = g.generate(ast, copy=c['copy'])
                results.append(dict(before=before, sql=sql, after=after, links=state,
                    again=again, final=dump(ast), reparsed=dump(parse_one(sql, read=d))))
            print(json.dumps(results))
            """, JsonSerializer.Serialize(cases)))!.AsArray();
        for (var i = 0; i < cases.Length; i++)
        {
            var c = cases[i];
            var d = Dialect.get_or_raise(c.dialect);
            var ast = Assert.Single(d.parse(c.sql))!;
            var before = serde.dump(ast);
            var g = d.generator(c.pretty);
            var sql = g.generate(ast, copy: c.copy);
            var after = serde.dump(ast);
            var links = Links(ast);
            var again = g.generate(ast, copy: c.copy);
            var observed = JsonSerializer.SerializeToNode(new
            {
                before, sql, after, links, again, final = serde.dump(ast),
                reparsed = serde.dump(Assert.Single(d.parse(sql)))
            }, serde.JsonOptions);
            Assert.True(JsonNode.DeepEquals(expected[i], observed),
                $"Case {i}: {c}\nPython: {expected[i]}\nC#: {observed}");
        }
    }

    [Fact]
    public async Task Malformed_order_and_missing_delimiters_match_public_Python_errors()
    {
        string[] bodies = [
            "id INT GENERATED ALWAYS AS IDENTITY (START WITH 1",
            "id INT GENERATED ALWAYS AS IDENTITY (INCREMENT BY 2 START WITH 1)",
            "id INT GENERATED ALWAYS AS IDENTITY (MAXVALUE 9 MINVALUE 1)",
            "id INT GENERATED ALWAYS AS IDENTITY (CYCLE INCREMENT BY 1)",
            "id INT GENERATED ALWAYS AS IDENTITY (START 1)",
            "id INT GENERATED BY AS IDENTITY",
            "id INT GENERATED ALWAYS AS IDENTITY (START WITH)",
            "id INT GENERATED ALWAYS AS IDENTITY (1,)",
            "id INT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 2)"
        ];
        var cases = bodies.SelectMany(body => new[] { "postgres", "timescale" }.SelectMany(dialect =>
            // Deferred recovery of out-of-order options reaches CREATE SEQUENCE
            // properties upstream; that larger grammar remains outside this port.
            (body.EndsWith("(START WITH 1", StringComparison.Ordinal)
                || body.EndsWith("(START WITH)", StringComparison.Ordinal)
                || body.EndsWith("(1,)", StringComparison.Ordinal)
                ? new[] { "IMMEDIATE", "RAISE", "IGNORE" } : new[] { "IMMEDIATE" })
            .Select(level => new { sql = $"CREATE TABLE t ({body})", dialect, level }))).ToArray();
        var expected = JsonNode.Parse(await Python("""
            import sys, json
            sys.path.insert(0, 'python'); sys.path.insert(0, 'src/tools')
            from oracle_plugins.timescale import Timescale
            from sqlglot.dialects import Dialect
            from sqlglot.errors import ParseError, ErrorLevel
            from sqlglot.serde import dump
            results = []
            for c in json.load(sys.stdin):
                ast, failure = None, None
                try: ast = [dump(n) for n in Dialect.get_or_raise(c['dialect']).parse(c['sql'], error_level=ErrorLevel[c['level']])]
                except ParseError as e: failure = e.errors
                results.append(dict(ast=ast, failure=failure))
            print(json.dumps(results))
            """, JsonSerializer.Serialize(cases)))!.AsArray();
        for (var i = 0; i < cases.Length; i++)
        {
            var c = cases[i];
            object? ast = null, failure = null;
            try { ast = Dialect.get_or_raise(c.dialect).parse(c.sql, Enum.Parse<errors.ErrorLevel>(c.level)).Select(serde.dump).ToArray(); }
            catch (errors.ParseError e) { failure = e.errors; }
            catch (NotPortedException e) { Assert.Fail($"Unexpected boundary: {c}: {e.Message}"); }
            var observed = JsonSerializer.SerializeToNode(new { ast, failure }, serde.JsonOptions);
            Assert.True(JsonNode.DeepEquals(expected[i], observed), $"{c}\nPython: {expected[i]}\nC#: {observed}");
        }
    }

    // Formerly NotPorted boundaries; behaviour now follows the Python oracle (read="postgres").
    [Theory]
    [InlineData("GENERATED ALWAYS AS ROW START", "CREATE TABLE t (id INT GENERATED ALWAYS AS ROW START)")]
    [InlineData("AS (1 + 2)", "CREATE TABLE t (id INT GENERATED ALWAYS AS ((1 + 2)) STORED)")]
    [InlineData("GENERATED ALWAYS AS (1 + 2) STORED", "CREATE TABLE t (id INT GENERATED ALWAYS AS (1 + 2) STORED)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (1, 2, 3)", "CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2))")]
    public void Identity_and_computed_clauses_match_upstream(string constraint, string expected) =>
        Assert.Equal(expected, Assert.Single(SqlGlot.Transpile($"CREATE TABLE t (id INT {constraint})", "postgres")));

    [Theory]
    [InlineData("GENERATED ALWAYS AS IDENTITY (NO MINVALUE)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY STORED")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (OWNED BY t.id)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (START WITH 1 CACHE 10)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (CACHE 10)")]
    [InlineData("GENERATED ALWAYS AS IDENTITY (START WITH 1 ORDER)")]
    public void Unknown_sequence_options_are_parse_errors_like_upstream(string constraint) =>
        Assert.Throws<errors.ParseError>(() => SqlGlot.Parse($"CREATE TABLE t (id INT {constraint})", "postgres"));

    [Theory]
    [InlineData("order", false)]
    [InlineData("expression", true)]
    [InlineData("cache", 10)]
    [InlineData("future_sequence_option", false)]
    public void Unsupported_generator_arguments_are_not_dropped(string key, object value)
    {
        foreach (var d in new[] { "postgres", "timescale" })
        {
            var node = new exp.GeneratedAsIdentityColumnConstraint(@this: true);
            node.set(key, value);
            Assert.Contains(key, Assert.Throws<NotPortedException>(() => Dialect.get_or_raise(d).generator().generate(node)).Message);
        }
    }

    private static async Task<string> Python(string script, string input, [CallerFilePath] string source = "")
    {
        var start = new ProcessStartInfo(Environment.GetEnvironmentVariable("SQLGLOT_PYTHON") ?? "python")
        {
            WorkingDirectory = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(source)!, "..", "..")),
            UseShellExecute = false, RedirectStandardInput = true, RedirectStandardOutput = true, RedirectStandardError = true
        };
        start.ArgumentList.Add("-B"); start.ArgumentList.Add("-c"); start.ArgumentList.Add(script);
        using var process = Process.Start(start)!;
        var stdout = process.StandardOutput.ReadToEndAsync(); var stderr = process.StandardError.ReadToEndAsync();
        using var timeout = new CancellationTokenSource(TimeSpan.FromMinutes(2));
        try
        {
            await process.StandardInput.WriteAsync(input.AsMemory(), timeout.Token);
            process.StandardInput.Close();
            await process.WaitForExitAsync(timeout.Token);
        }
        catch (OperationCanceledException) { process.Kill(entireProcessTree: true); throw; }
        Assert.True(process.ExitCode == 0, await stderr);
        return await stdout;
    }
